const DEFAULT_CURRENCY = "USD";
const CPI_CURRENT_YEAR = 2026; // "today" reference for badges when no year is picked

function cpiConvert(amount, fromYear, toYear, currencyCode) {
  const currency = CURRENCIES[currencyCode];
  if (!currency) return null;
  const from = currency.data[fromYear];
  const to = currency.data[toYear];
  if (!from || !to) return null;
  return amount * (to / from);
}

// Clamp a requested year into the valid range for a given currency, so a
// UK price still gets a sensible comparison even if the picked year (say,
// 1920) predates GBP's series start.
function clampYearForCurrency(year, currencyCode) {
  const currency = CURRENCIES[currencyCode];
  if (!currency) return year;
  return Math.min(currency.maxYear, Math.max(currency.minYear, year));
}

